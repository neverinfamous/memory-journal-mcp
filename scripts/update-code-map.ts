import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

import { getTools } from '../src/handlers/tools/index.js'
import { getResources } from '../src/handlers/resources/index.js'
import { getPrompts } from '../src/handlers/prompts/index.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')

function updateCodeMap() {
    const codeMapPath = path.join(ROOT, 'test-server/code-map.md')
    if (!fs.existsSync(codeMapPath)) {
        console.error('code-map.md not found at', codeMapPath)
        process.exit(1)
    }

    let content = fs.readFileSync(codeMapPath, 'utf-8')
    if (!content.includes('AUTO-GENERATED BY scripts/update-code-map.ts')) {
        content = `<!-- AUTO-GENERATED BY scripts/update-code-map.ts. DO NOT EDIT MANUALLY. -->\n\n${content}`
    }

    // Generate Tools Markdown
    // getTools requires a DB context, but the definitions are built inside closures
    // so we can safely pass dummy objects to get the metadata arrays.
    const rawTools = getTools({} as any, null)
    
    // Group tools by their icon title to provide a clean, human-readable grouping
    const toolsByGroup = new Map<string, Set<string>>()
    for (const t of rawTools) {
        const groupTitle = t.icons?.title || 'Other'
        if (!toolsByGroup.has(groupTitle)) {
            toolsByGroup.set(groupTitle, new Set())
        }
        toolsByGroup.get(groupTitle)!.add(t.name)
    }

    let toolsMd = '| Group | Tools |\n| ----- | ----- |\n'
    const sortedGroups = Array.from(toolsByGroup.keys()).sort()
    for (const group of sortedGroups) {
        const toolList = Array.from(toolsByGroup.get(group)!).map(t => `\`${t}\``).join(', ')
        toolsMd += `| **${group}** | ${toolList} |\n`
    }

    // Generate Resources Markdown
    const resources = getResources() as { uri: string; name: string }[]
    let resourcesMd = '| URI | Name |\n| --- | ---- |\n'
    
    // Sort resources by URI for consistent output
    const sortedResources = [...resources].sort((a, b) => a.uri.localeCompare(b.uri))
    for (const res of sortedResources) {
        resourcesMd += `| \`${res.uri}\` | ${res.name} |\n`
    }

    // Generate Prompts Markdown
    const prompts = getPrompts() as { name: string; description: string }[]
    let promptsMd = '| Prompt | Description |\n| ------ | ----------- |\n'
    
    // Sort prompts by name for consistent output
    const sortedPrompts = [...prompts].sort((a, b) => a.name.localeCompare(b.name))
    for (const p of sortedPrompts) {
        const cleanDesc = p.description.replace(/\n/g, ' ')
        const truncDesc = cleanDesc.length > 80 ? cleanDesc.substring(0, 80) + '...' : cleanDesc
        promptsMd += `| \`${p.name}\` | ${truncDesc} |\n`
    }

    // Inject into markers
    content = content.replace(/<!-- BEGIN: TOOL_MAPPING -->[\s\S]*?<!-- END: TOOL_MAPPING -->/, `<!-- BEGIN: TOOL_MAPPING -->\n${toolsMd}<!-- END: TOOL_MAPPING -->`)
    content = content.replace(/<!-- BEGIN: RESOURCES -->[\s\S]*?<!-- END: RESOURCES -->/, `<!-- BEGIN: RESOURCES -->\n${resourcesMd}<!-- END: RESOURCES -->`)
    content = content.replace(/<!-- BEGIN: PROMPTS -->[\s\S]*?<!-- END: PROMPTS -->/, `<!-- BEGIN: PROMPTS -->\n${promptsMd}<!-- END: PROMPTS -->`)

    fs.writeFileSync(codeMapPath, content)
    console.log('code-map.md updated successfully.')
}

updateCodeMap()
