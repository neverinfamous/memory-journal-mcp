import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

import type { IDatabaseAdapter } from '../src/database/core/interfaces.js'
import { getTools } from '../src/handlers/tools/index.js'

function isToolCatalogAdapter(value: unknown): value is IDatabaseAdapter {
    return typeof value === 'object' && value !== null
}

function toolCatalogAdapter(): IDatabaseAdapter {
    const target: object = Object.create(null)
    const proxy: unknown = new Proxy(target, {
        get(_obj, property) {
            if (property === 'then') return undefined
            return () => {
                throw new Error(`Tool catalog adapter does not implement ${String(property)}`)
            }
        },
    })
    if (!isToolCatalogAdapter(proxy)) {
        throw new Error('Tool catalog adapter was not created')
    }
    return proxy
}
import { getResources } from '../src/handlers/resources/index.js'
import { getPrompts } from '../src/handlers/prompts/index.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')

function updateCodeMap() {
    const codeMapPath = path.join(ROOT, 'test-server/code-map.md')
    let content: string
    try {
        content = fs.readFileSync(codeMapPath, 'utf-8')
    } catch (error) {
        if (typeof error === 'object' && error !== null && 'code' in error && error.code === 'ENOENT') {
            console.error('code-map.md not found at', codeMapPath)
            process.exit(1)
        }
        throw error
    }
    if (!content.includes('AUTO-GENERATED BY scripts/update-code-map.ts')) {
        content = `<!-- AUTO-GENERATED BY scripts/update-code-map.ts. DO NOT EDIT MANUALLY. -->\n\n${content}`
    }

    // Generate Tools Markdown
    // getTools requires a DB context, but the definitions are built inside closures
    // so we can safely pass dummy objects to get the metadata arrays.
    const rawTools = getTools(toolCatalogAdapter(), null, undefined, undefined, { agentHealing: false })
    
    // Group tools by their icon title to provide a clean, human-readable grouping
    const toolsByGroup = new Map<string, Set<string>>()
    for (const t of rawTools) {
        const groupTitle = t.icons?.title || 'Other'
        let groupSet = toolsByGroup.get(groupTitle)
        if (groupSet === undefined) {
            groupSet = new Set()
            toolsByGroup.set(groupTitle, groupSet)
        }
        groupSet.add(t.name)
    }

    let toolsMd = '| Group | Tools |\n| ----- | ----- |\n'
    const sortedGroups = Array.from(toolsByGroup.keys()).sort()
    for (const group of sortedGroups) {
        const groupTools = toolsByGroup.get(group) ?? new Set<string>()
        const toolList = Array.from(groupTools).map(t => `\`${t}\``).join(', ')
        toolsMd += `| **${group}** | ${toolList} |\n`
    }

    // Generate Resources Markdown
    const resources = getResources() as { uri: string; name: string }[]
    let resourcesMd = '| URI | Name |\n| --- | ---- |\n'
    
    // Sort resources by URI for consistent output
    const sortedResources = [...resources].sort((a, b) => a.uri.localeCompare(b.uri))
    for (const res of sortedResources) {
        resourcesMd += `| \`${res.uri}\` | ${res.name} |\n`
    }

    // Generate Prompts Markdown
    const prompts = getPrompts() as { name: string; description: string }[]
    let promptsMd = '| Prompt | Description |\n| ------ | ----------- |\n'
    
    // Sort prompts by name for consistent output
    const sortedPrompts = [...prompts].sort((a, b) => a.name.localeCompare(b.name))
    for (const p of sortedPrompts) {
        const cleanDesc = p.description.replace(/\n/g, ' ')
        const truncDesc = cleanDesc.length > 80 ? cleanDesc.substring(0, 80) + '...' : cleanDesc
        promptsMd += `| \`${p.name}\` | ${truncDesc} |\n`
    }

    // Inject into markers (fail explicitly if any marker pair is missing so drift cannot pass silently)
    const toolMarker = /<!-- BEGIN: TOOL_MAPPING -->[\s\S]*?<!-- END: TOOL_MAPPING -->/
    const resourceMarker = /<!-- BEGIN: RESOURCES -->[\s\S]*?<!-- END: RESOURCES -->/
    const promptMarker = /<!-- BEGIN: PROMPTS -->[\s\S]*?<!-- END: PROMPTS -->/
    for (const [label, pattern] of [
        ['TOOL_MAPPING', toolMarker],
        ['RESOURCES', resourceMarker],
        ['PROMPTS', promptMarker],
    ] as const) {
        if (!pattern.test(content)) {
            throw new Error(`Missing code-map marker block for ${label} in ${codeMapPath}`)
        }
    }
    content = content.replace(toolMarker, `<!-- BEGIN: TOOL_MAPPING -->\n${toolsMd}<!-- END: TOOL_MAPPING -->`)
    content = content.replace(resourceMarker, `<!-- BEGIN: RESOURCES -->\n${resourcesMd}<!-- END: RESOURCES -->`)
    content = content.replace(promptMarker, `<!-- BEGIN: PROMPTS -->\n${promptsMd}<!-- END: PROMPTS -->`)

    fs.writeFileSync(codeMapPath, content)
    console.log('code-map.md updated successfully.')
}

updateCodeMap()
